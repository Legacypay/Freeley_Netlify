// Self-hosts the Google Fonts that src/layouts/Layout.astro and the legacy
// public/promo-*.html pages used to link from fonts.googleapis.com (FRLY-9):
// that cross-origin stylesheet was the largest render-blocking request on
// those pages (~0.8-0.9 s on Lighthouse's mobile profile). This downloads the
// exact CSS Google serves to a modern Chrome (woff2, unicode-range subsets,
// font-display: swap) and every font file it references, then rewrites the
// URLs to /fonts/google/. Same files, same @font-face rules, same rendering;
// one origin fewer.
//
//   node scripts/self-host-google-fonts.mjs
//
// Re-run only to change a family set below (and keep its page in sync).
import { mkdirSync, writeFileSync } from 'node:fs';

// One generated stylesheet per family set; font files are shared in OUT.
const SETS = [
  {
    // src/layouts/Layout.astro
    css: 'fonts.css',
    url: 'https://fonts.googleapis.com/css2?family=Archivo:wght@400..700&family=Archivo+Narrow:wght@400..700&family=Inter:ital,opsz,wght@0,14..32,100..900;1,14..32,100..900&family=Playfair+Display:ital,wght@0,400..900;1,400..900&family=Poppins:ital,wght@0,100;0,200;0,300;0,400;0,500;0,600;0,700;0,800;0,900;1,100;1,200;1,300;1,400;1,500;1,600;1,700;1,800;1,900&family=Source+Serif+4:ital,wght@0,400..700;1,400..700&display=swap',
  },
  {
    // public/promo-{weight-loss,ed,hair-loss,longevity}.html
    css: 'fonts-promo.css',
    url: 'https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,300;0,400;0,600;1,300;1,400;1,600&family=Montserrat:wght@400;500;600;700&family=DM+Sans:opsz,wght@9..40,300;9..40,400;9..40,500;9..40,600&display=swap',
  },
  {
    // public/shared.css @import (legacy public/*.html pages, /hub, LegalArticle)
    css: 'fonts-shared.css',
    url: 'https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,300;0,400;0,600;1,300;1,400;1,600&family=DM+Sans:opsz,wght@9..40,300;9..40,400;9..40,500;9..40,600&family=Playfair+Display:wght@700;800;900&display=swap',
  },
];
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36';
const OUT = 'public/fonts/google';

mkdirSync(OUT, { recursive: true });
for (const set of SETS) {
  const css = await (await fetch(set.url, { headers: { 'user-agent': UA } })).text();
  const urls = [...new Set([...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map((m) => m[1]))];

  let local = css;
  for (const url of urls) {
    // https://fonts.gstatic.com/s/<family>/<version>/<file>.woff2 -> /fonts/google/<family>-<version>-<file>.woff2
    const [, family, version, file] = url.match(/\/s\/([^/]+)\/([^/]+)\/(.+)$/);
    const name = `${family}-${version}-${file}`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${res.status} ${url}`);
    writeFileSync(`${OUT}/${name}`, Buffer.from(await res.arrayBuffer()));
    local = local.split(url).join(`/fonts/google/${name}`);
  }

  writeFileSync(
    `${OUT}/${set.css}`,
    `/* Generated by scripts/self-host-google-fonts.mjs from:\n   ${set.url}\n   Do not edit by hand. */\n${local}`,
  );
  console.log(`${urls.length} font files + ${OUT}/${set.css}`);
}
